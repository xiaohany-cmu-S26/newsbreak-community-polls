"""Export every poll (and every declined article) to a readable Markdown file.

  .venv/bin/python -m scripts.export_polls [out.md]"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from backend import db  # noqa: E402


def main(out_path):
    polls = db.list_polls(limit=1000)
    with db.connect() as c:
        arts = [dict(r) for r in c.execute("SELECT * FROM articles ORDER BY created_at").fetchall()]
    by_poll = {}
    for a in arts:
        if a["poll_id"]:
            by_poll.setdefault(a["poll_id"], []).append(a)
    lines = ["# Community polls export", ""]
    lines.append(f"{len(polls)} polls, {sum(1 for a in arts if a['pollable'] == 0)} declined articles.")
    lines.append("")
    for i, p in enumerate(polls, 1):
        counts = db.vote_counts(p["poll_id"], len(p["options"]))
        total = sum(counts)
        origin = "hand-seeded for the demo" if "hand-seeded" in str((p.get("usage") or {}).get("note", "")) else \
            f"generated by the agent ({(p.get('usage') or {}).get('n_calls', '?')} model calls, ${(p.get('usage') or {}).get('cost_usd', 0)})"
        lines.append(f"## {i}. {p['question']}")
        lines.append("")
        lines.append(f"*{p['city']} · {origin} · id `{p['poll_id']}`*")
        lines.append("")
        for a in by_poll.get(p["poll_id"], []):
            lines.append(f"- Article: [{a['headline']}]({a['url']})")
        lines.append("")
        lines.append(f"**Options** ({total} votes{', simulated' if total else ''}):")
        lines.append("")
        for o, n in zip(p["options"], counts):
            pct = f" — {n} ({round(100 * n / total)}%)" if total else ""
            lines.append(f"- {o}{pct}")
        lines.append("")
        lines.append(f"**The case for:** {p['context'].get('for', '')}")
        lines.append("")
        lines.append(f"**The case against:** {p['context'].get('against', '')}")
        lines.append("")
        lines.append(f"**Who can vote:** ZIPs {', '.join(p['geo_scope']) or 'anyone'}"
                     + (f" · **Decision date:** {p['decision_date']}" if p.get("decision_date") else ""))
        lines.append("")
        if p["critic_log"]:
            lines.append(f"**Critic:** {p['critic_passes']} pass(es), final draft {'accepted' if p['critic_passed'] else 'still flagged'}")
            for c in p["critic_log"]:
                lines.append(f"- attempt {c['attempt']}: {'PASS' if c['passed'] else 'FAIL'} — {c['summary']}")
                for iss in c.get("issues", []):
                    lines.append(f"    - *{iss['type']}*: {iss['detail']}")
                if not c["passed"] and c.get("draft"):
                    lines.append(f"    - draft question was: \"{c['draft']['question']}\"  options: {c['draft']['options']}")
            lines.append("")
        if p["sources"]:
            lines.append("**Sources:** " + ", ".join(p["sources"]))
            lines.append("")
        lines.append("---")
        lines.append("")
    declined = [a for a in arts if a["pollable"] == 0]
    if declined:
        lines.append("## Declined articles (no poll)")
        lines.append("")
        import json
        for a in declined:
            t = json.loads(a["triage"]) if a.get("triage") else {}
            lines.append(f"- [{a['headline']}]({a['url']}) — **{t.get('category', '?')}**: {t.get('reason', '')}")
        lines.append("")
    open(out_path, "w").write("\n".join(lines))
    print(f"wrote {out_path}: {len(polls)} polls, {len(declined)} declined")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "polls_export.md"))
